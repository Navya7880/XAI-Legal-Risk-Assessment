def generate_hiring_dataset(
    n_samples: int = 1600,
    random_state: int = 73,
) -> pd.DataFrame:

    """Create synthetic hiring data for fairness testing."""

    if n_samples < 100:
        raise ValueError(
            "n_samples must be at least 100."
        )

    rng = np.random.default_rng(random_state)

    synthetic_group = rng.choice(
        ["Group A", "Group B"],
        n_samples,
        p=[0.55, 0.45],
    )
    gender = np.where(
        synthetic_group == "Group A",
        rng.choice(["Woman", "Man"], n_samples, p=[0.58, 0.42]),
        rng.choice(["Woman", "Man"], n_samples, p=[0.42, 0.58]),
    )

    education = rng.choice(
        ["high_school", "bachelors", "masters"],
        n_samples,
        p=[0.25, 0.53, 0.22],
    )

    experience_years = np.clip(
        rng.normal(5.5, 3.1, n_samples),
        0,
        20,
    ).round(1)

    technical_score = np.clip(
        rng.normal(68, 15, n_samples),
        0,
        100,
    ).round(1)

    assessment_score = np.clip(
        rng.normal(70, 14, n_samples),
        0,
        100,
    ).round(1)

    referral_network_score = np.clip(
        np.where(
            synthetic_group == "Group A",
            68.0,
            38.0,
        )
        + rng.normal(0, 12, n_samples),
        0,
        100,
    ).round(1)

    education_points = np.select(
        [
            education == "high_school",
            education == "bachelors",
        ],
        [
            0.0,
            0.55,
        ],
        default=0.9,
    )

    # Group-dependent label term intentionally provides
    # a controlled fairness-audit example.
    logit = (
        -5.4
        + education_points
        + 0.10 * experience_years
        + 0.035 * technical_score
        + 0.030 * assessment_score
        + (synthetic_group == "Group A") * 0.65
        + rng.normal(0, 0.65, n_samples)
    )

    hired = np.where(
        logit >= np.median(logit),
        "Yes",
        "No",
    )

    return pd.DataFrame(
        {
            "education": education,
            "experience_years": experience_years,
            "technical_score": technical_score,
            "assessment_score": assessment_score,
            "referral_network_score": referral_network_score,
            HIRING_SENSITIVE: synthetic_group,
            HIRING_GENDER: gender,
            HIRING_TARGET: hired,
        }
    )


# --------------------------------------------------
# DATASET VALIDATION
# --------------------------------------------------

def validate_dataset(
    data: pd.DataFrame,
    dataset_name: str,
) -> bool:

    """Check whether a dataset contains its configured columns."""

    if dataset_name not in DATASET_CONFIG:
        raise ValueError(
            f"Unknown dataset: {dataset_name}"
        )

    config = DATASET_CONFIG[dataset_name]

    required_columns = (
        config["features"]
        + [config["target"]]
        + ([config["sensitive"]] if config.get("sensitive") else [])
    )

    missing = [
        column
        for column in required_columns
        if column not in data.columns
    ]

    if missing:
        raise ValueError(
            f"Dataset is missing required columns: {', '.join(missing)}"
        )

    if data.empty:
        raise ValueError(
            "Dataset cannot be empty."
        )

    if data[config["target"]].dropna().nunique() < 2:
        raise ValueError(
            "Dataset target must contain at least two classes."
        )

    return True


