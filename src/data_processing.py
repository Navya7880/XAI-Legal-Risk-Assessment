# LOAD OR GENERATE DATASETS
# --------------------------------------------------

def ensure_datasets(
    data_dir: Path = DATA_DIR,
) -> dict[str, pd.DataFrame]:

    """
    Load existing CSV files or generate reproducible
    synthetic datasets when files are unavailable or invalid.
    """

    data_dir = Path(data_dir)

    data_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    generators = {
        "Legal risk (synthetic)": (
            "synthetic_legal_risk.csv",
            generate_legal_dataset,
        ),

        "Hiring (synthetic)": (
            "synthetic_hiring.csv",
            generate_hiring_dataset,
        ),
    }

    datasets: dict[str, pd.DataFrame] = {}

    for name, (filename, generator) in generators.items():

        path = data_dir / filename

        regenerate = not path.exists()

        if not regenerate:
            try:
                existing_data = pd.read_csv(path)

                validate_dataset(
                    existing_data,
                    name,
                )

                datasets[name] = existing_data

            except (
                ValueError,
                pd.errors.ParserError,
                pd.errors.EmptyDataError,
                UnicodeDecodeError,
            ):
                regenerate = True

        if regenerate:
            generated_data = generator()

            validate_dataset(
                generated_data,
                name,
            )

            generated_data.to_csv(
                path,
                index=False,
            )

            datasets[name] = generated_data

    return datasets


