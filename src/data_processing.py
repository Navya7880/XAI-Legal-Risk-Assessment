# LEGAL RISK SYNTHETIC DATASET
# --------------------------------------------------

def generate_legal_dataset(
    n_samples: int = 1200,
    random_state: int = 42,
) -> pd.DataFrame:

    """Create a fictional legal-risk dataset."""

    if n_samples < 100:
        raise ValueError(
            "n_samples must be at least 100."
        )

    rng = np.random.default_rng(random_state)

    age = rng.integers(
        18,
        71,
        n_samples,
    )

    prior_offenses = np.minimum(
        rng.poisson(0.8, n_samples),
        6,
    )

    offense_category = rng.choice(
        ["property", "drug", "traffic", "violent"],
        n_samples,
        p=[0.32, 0.22, 0.31, 0.15],
    )

    employment_status = rng.choice(
        ["employed", "unemployed", "student"],
        n_samples,
        p=[0.62, 0.27, 0.11],
    )

    education_level = rng.choice(
        ["secondary", "certificate", "college", "graduate"],
        n_samples,
        p=[0.42, 0.25, 0.24, 0.09],
    )
    program_completion = rng.choice(
        ["yes", "no"],
        n_samples,
        p=[0.38, 0.62],
    )
    substance_treatment = rng.choice(
        ["completed", "not_completed", "not_needed"],
        n_samples,
        p=[0.25, 0.35, 0.40],
    )
    legal_group = rng.choice(
        ["Group A", "Group B"],
        n_samples,
        p=[0.50, 0.50],
    )

    score = (
        0.90 * prior_offenses
        + np.isin(
            offense_category,
            ["violent", "property"],
        ) * 0.75
        + (employment_status == "unemployed") * 0.35
        - (employment_status == "employed") * 0.18
        - (education_level == "certificate") * 0.05
        - (education_level == "college") * 0.12
        - (education_level == "graduate") * 0.18
        - (program_completion == "yes") * 0.25
        - (substance_treatment == "completed") * 0.20
        - (age >= 45) * 0.20
        + rng.normal(0, 0.8, n_samples)
    )

    threshold = float(
        np.quantile(score, 0.56)
    )

    risk_category = np.where(
        score >= threshold,
        "Elevated",
        "Lower",
    )

    return pd.DataFrame(
        {
            "age": age,
            "prior_offenses": prior_offenses,
            "offense_category": offense_category,
            "employment_status": employment_status,
            "education_level": education_level,
            "program_completion": program_completion,
            "substance_treatment": substance_treatment,
            LEGAL_PROTECTED: legal_group,
            LEGAL_TARGET: risk_category,
        }
    )


