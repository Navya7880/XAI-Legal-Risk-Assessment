# LOAD PUBLIC LEGAL DATASET
# --------------------------------------------------

def load_public_legal_dataset(
    path: str | Path,
    column_mapping: dict[str, str],
) -> pd.DataFrame:

    """
    Load a user-provided legal CSV using explicit
    normalized-column mappings.
    """

    required = LEGAL_FEATURES + [LEGAL_TARGET]

    missing_mapping = [
        column
        for column in required
        if column not in column_mapping
    ]

    if missing_mapping:
        raise ValueError(
            "Missing column mappings for: "
            + ", ".join(missing_mapping)
        )

    sources = [
        column_mapping[column]
        for column in required
    ]

    if not all(
        isinstance(column, str) and column.strip()
        for column in sources
    ):
        raise ValueError(
            "Source column mappings must be non-empty strings."
        )

    if len(set(sources)) != len(sources):
        raise ValueError(
            "Each normalized field must map to a distinct source column."
        )

    raw = pd.read_csv(path)

    missing_sources = [
        column
        for column in sources
        if column not in raw.columns
    ]

    if missing_sources:
        raise ValueError(
            "Missing source columns: "
            + ", ".join(missing_sources)
        )

    normalized = raw[sources].copy()

    normalized.columns = required

    normalized = normalized.dropna(
        subset=[LEGAL_TARGET]
    ).reset_index(drop=True)

    if normalized.empty:
        raise ValueError(
            "The uploaded dataset has no rows with a valid target."
        )

    return normalized
