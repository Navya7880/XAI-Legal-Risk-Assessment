"""PDF transparency and research assessment report generation."""

from __future__ import annotations

from datetime import datetime, timezone
from html import escape
from io import BytesIO
from typing import Any

import pandas as pd
from reportlab.lib import colors
from reportlab.lib.pagesizes import landscape, letter
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    LongTable,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    TableStyle,
)


def generate_pdf_report(
    dataset_name: str,
    model_name: str,
    metrics: dict[str, Any],
    fairness: dict[str, Any] | None = None,
    prediction: dict[str, Any] | None = None,
    counterfactuals: pd.DataFrame | None = None,
    dataset_data: pd.DataFrame | None = None,
    target_column: str | None = None,
    feature_columns: list[str] | None = None,
    model_result: dict[str, Any] | None = None,
    counterfactual_quality: dict[str, float] | None = None,
    counterfactual_run: bool = False,
) -> bytes:
    buffer = BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=landscape(letter),
        title="XAI Research Assessment",
        leftMargin=36,
        rightMargin=36,
    )
    styles = getSampleStyleSheet()
    body = styles["BodyText"]
    story = [
        Paragraph("XAI Model Transparency & Research Assessment", styles["Title"]),
        Paragraph(
            f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
            body,
        ),
        Spacer(1, 10),
        Paragraph("1. Study overview", styles["Heading2"]),
        Paragraph(
            "Academic demonstrator for model interpretation using synthetic decision-support "
            "examples. It is not for decisions about real people.",
            body,
        ),
        Paragraph("2. Dataset information", styles["Heading2"]),
    ]

    dataset_rows = [
        ["Item", "Details"],
        ["Dataset", _safe(dataset_name)],
        [
            "Source",
            (
                "Synthetic, generated for this demo"
                if dataset_name.endswith("(synthetic)")
                else "User-provided; source and licence must be independently verified"
            ),
        ],
        ["Rows", str(len(dataset_data)) if dataset_data is not None else "Not provided"],
        ["Features", ", ".join(feature_columns or []) or "Not provided"],
        ["Target", target_column or "Not provided"],
        [
            "Class balance",
            _class_balance(dataset_data, target_column),
        ],
        [
            "Synthetic-data statement",
            (
                "Legal labels are generated by a hand-written rule plus noise; hiring labels "
                "are also synthetic. Accuracy shows rule recovery in this sample, not "
                "real-world predictive validity."
                if dataset_name == "Legal risk (synthetic)"
                else "All included outcomes and group attributes are synthetic."
                if dataset_name.endswith("(synthetic)")
                else "This report uses user-provided real public data; verify source, licence, "
                "provenance, and known limitations."
            ),
        ],
    ]
    story.append(_styled_table(dataset_rows, [135, 585], body))

    story.extend(
        [
            Paragraph("3. Model details", styles["Heading2"]),
            Paragraph(f"Classifier: {_safe(model_name)}.", body),
            Paragraph(
                "Preprocessing: numeric median imputation and standard scaling; categorical "
                "most-frequent imputation and one-hot encoding, all fitted inside the "
                "training-only scikit-learn pipeline.",
                body,
            ),
        ]
    )
    if model_result is not None:
        classifier = model_result["pipeline"].named_steps.get("classifier")
        params = classifier.get_params(deep=False) if classifier is not None else {}
        relevant = {
            key: value
            for key, value in params.items()
            if key in {
                "n_estimators",
                "max_depth",
                "min_samples_leaf",
                "class_weight",
                "max_iter",
                "learning_rate",
                "random_state",
            }
        }
        if relevant:
            story.append(
                _styled_table(
                    [["Hyperparameter", "Value"]]
                    + [[_safe(key), _safe(value)] for key, value in relevant.items()],
                    [180, 540],
                    body,
                )
            )

    story.extend(
        [
            Paragraph("4. Evaluation results", styles["Heading2"]),
            Paragraph("Metrics below are computed from the held-out test split.", body),
            _styled_table(_metric_rows(metrics), [250, 470], body),
        ]
    )
    confusion = metrics.get("confusion_matrix")
    labels = metrics.get("labels")
    if confusion and labels:
        story.append(Paragraph("Confusion matrix", styles["Heading3"]))
        story.append(
            _styled_table(
                [["Actual / Predicted", *[_safe(label) for label in labels]]]
                + [
                    [_safe(label), *[str(value) for value in row]]
                    for label, row in zip(labels, confusion)
                ],
                body_style=body,
            )
        )

    story.extend(
        [
            Paragraph("5. DiCE results", styles["Heading2"]),
            Paragraph(
                (
                    f"Original model prediction: {_safe(prediction.get('prediction', 'Not provided'))}."
                    if prediction
                    else "No individual prediction was recorded in this session."
                ),
                body,
            ),
            Paragraph(
                "Counterfactuals are hypothetical model-specific changes, not causal claims, "
                "recommendations, or guarantees.",
                body,
            ),
        ]
    )
    if counterfactual_quality is not None:
        story.append(
            _styled_table(
                [["Quality metric", "Value"]]
                + [
                    [_safe(name.replace("_", " ").title()), f"{value:.4f}"]
                    for name, value in counterfactual_quality.items()
                ],
                [250, 470],
                body,
            )
        )
    if counterfactual_run:
        if counterfactuals is None or counterfactuals.empty:
            story.append(Paragraph("DiCE ran; no valid counterfactual was returned.", body))
        else:
            story.append(_counterfactual_table(counterfactuals, document.width, body))
    else:
        story.append(Paragraph("No DiCE run was recorded in this session.", body))

    story.append(Paragraph("6. Fairness results", styles["Heading2"]))
    fairness_story = _fairness_section(fairness, body)
    if isinstance(fairness_story, list):
        story.extend(fairness_story)
    else:
        story.append(fairness_story)
    story.extend(
        [
            Paragraph("7. Transparency checklist", styles["Heading2"]),
            _styled_table(
                _checklist_rows(
                    dataset_data is not None,
                    bool(metrics),
                    counterfactual_run,
                    fairness is not None,
                ),
                [225, 495],
                body,
            ),
            Paragraph("8. Risks and limitations", styles["Heading2"]),
            Paragraph(
                "Synthetic data cannot represent real populations, legal standards, or hiring "
                "practices. Accuracy can reflect synthetic rule recovery. DiCE describes model "
                "behavior and does not establish causality or feasible interventions. Fairness "
                "metrics can conflict with each other and with accuracy; mitigation does not "
                "prove real-world fairness.",
                body,
            ),
            Paragraph("9. Human-oversight recommendations", styles["Heading2"]),
            Paragraph(
                "Do not use this demonstrator to make, recommend, or justify decisions about "
                "real people. Any separate real-world system requires context-specific "
                "validation, qualified human review, governance, monitoring, and independent "
                "legal, privacy, security, and impact assessment.",
                body,
            ),
            Paragraph("Regulatory considerations (not legal conclusions)", styles["Heading3"]),
            Paragraph(
                "Depending on context, GDPR Articles 13–15 concern information and access "
                "rights; Article 22 addresses certain solely automated decisions and related "
                "safeguards. EU AI Act obligations for high-risk systems may include data "
                "governance, record-keeping/logging, transparency, and human oversight. "
                "Applicability requires qualified legal analysis.",
                body,
            ),
            Spacer(1, 8),
            Paragraph(
                "This report supports a preliminary compliance assessment and does not certify "
                "GDPR or EU AI Act compliance.",
                styles["Italic"],
            ),
        ]
    )
    document.build(story)
    return buffer.getvalue()


def _safe(value: Any) -> str:
    return escape(str(value))


def _class_balance(data: pd.DataFrame | None, target: str | None) -> str:
    if data is None or target is None or target not in data:
        return "Not provided"
    counts = data[target].value_counts(dropna=False, normalize=True)
    return "; ".join(f"{label}: {ratio:.1%}" for label, ratio in counts.items())


def _metric_rows(metrics: dict[str, Any]) -> list[list[str]]:
    rows = [["Metric", "Value"]]
    for key in ("accuracy", "precision", "recall", "f1", "roc_auc"):
        if key in metrics:
            rows.append([key.replace("_", " ").title(), f"{metrics[key]:.4f}"])
    return rows


def _styled_table(
    rows: list[list[Any]],
    col_widths: list[float] | None = None,
    body_style: Any = None,
) -> LongTable:
    styles = getSampleStyleSheet()
    cell_style = body_style or styles["BodyText"]
    wrapped = [
        [
            cell
            if isinstance(cell, Paragraph)
            else Paragraph(_safe(cell), cell_style)
            for cell in row
        ]
        for row in rows
    ]
    table = LongTable(
        wrapped,
        colWidths=col_widths,
        repeatRows=1,
        hAlign="LEFT",
    )
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#146C65")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#B8CDE0")),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F0F5FA")]),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("FONTSIZE", (0, 0), (-1, -1), 8),
                ("LEFTPADDING", (0, 0), (-1, -1), 5),
                ("RIGHTPADDING", (0, 0), (-1, -1), 5),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    return table


def _counterfactual_table(
    counterfactuals: pd.DataFrame,
    available_width: float,
    body_style: Any,
) -> LongTable:
    headers = ["Counterfactual", *[str(column) for column in counterfactuals.columns]]
    rows: list[list[Any]] = [headers]
    rows.extend(
        [
            [str(index + 1), *[str(value) for value in row]]
            for index, row in enumerate(counterfactuals.itertuples(index=False, name=None))
        ]
    )
    widths = [available_width / len(headers)] * len(headers)
    return _styled_table(rows, widths, body_style)


def _fairness_section(fairness: dict[str, Any] | None, body: Any) -> Any:
    if not fairness:
        return Paragraph("No fairness audit artifact was recorded in this session.", body)
    if "comparison" in fairness and fairness.get("comparison") is not None:
        comparison = fairness["comparison"]
        rows = [list(comparison.columns)] + [
            [str(value) for value in row]
            for row in comparison.itertuples(index=False, name=None)
        ]
        components = [
            Paragraph(
                f"ThresholdOptimizer constraint: {_safe(fairness.get('constraint', 'Not recorded'))}.",
                body,
            ),
            _styled_table(rows, body_style=body),
        ]
        reference_comparison = fairness.get("reference_comparison")
        if reference_comparison is not None:
            components.extend(
                [
                    Paragraph(
                        "Reference model including group attribute (not recommended)",
                        body,
                    ),
                    _styled_table(
                        [list(reference_comparison.columns)]
                        + [
                            [str(value) for value in row]
                            for row in reference_comparison.itertuples(
                                index=False, name=None
                            )
                        ],
                        body_style=body,
                    ),
                ]
            )
        after = fairness.get("after")
        if after is not None:
            components.append(Paragraph("Post-mitigation group metrics and confidence intervals", body))
            components.append(
                _styled_table(
                    [
                        ["Group", *list(after["by_group"].columns)]
                    ]
                    + [
                        [str(group), *[f"{value:.4f}" for value in row]]
                        for group, row in after["by_group"].iterrows()
                    ],
                    body_style=body,
                )
            )
            lower, upper = after["demographic_parity_difference_ci"]
            components.append(
                Paragraph(
                    f"Post-mitigation demographic-parity-difference 95% CI: "
                    f"{lower:.4f}–{upper:.4f}.",
                    body,
                )
            )
        elif fairness.get("mitigation_error"):
            components.append(
                Paragraph(
                    "Mitigation could not run: "
                    f"{_safe(fairness['mitigation_error'])}",
                    body,
                )
            )
        return components
    return Paragraph(
        f"Demographic parity difference: "
        f"{fairness.get('demographic_parity_difference', float('nan')):.4f}; "
        f"equalized odds difference: "
        f"{fairness.get('equalized_odds_difference', float('nan')):.4f}.",
        body,
    )


def _checklist_rows(
    dataset_exists: bool,
    metrics_exist: bool,
    counterfactual_exists: bool,
    fairness_exists: bool,
) -> list[list[str]]:
    checks = [
        ("Dataset details", dataset_exists, "dataset information is available", "dataset data was not supplied"),
        ("Held-out metrics", metrics_exist, "model metrics are available", "model metrics are missing"),
        ("DiCE explanation", counterfactual_exists, "a DiCE run exists in the current session", "no DiCE run exists in the current session"),
        ("Fairness audit", fairness_exists, "a fairness audit exists in the current session", "no fairness audit exists in the current session"),
        ("Context-specific assessment", False, "", "no legal, privacy, or impact assessment artifact is recorded"),
    ]
    return [
        ["Artifact", "Status and evidence"],
        *[
            [
                label,
                f"{'Recorded' if present else 'Not recorded'}: "
                f"{evidence if present else missing}",
            ]
            for label, present, evidence, missing in checks
        ],
    ]
